"""Builds dist/ from src/:
  dist/install_animkit.luau  - paste into MCP execute_luau (Edit mode) -> ServerStorage.AnimKit
  dist/AnimKit.rbxmx         - model file, drag into ServerStorage
  dist/AnimKitPlugin.rbxmx   - local plugin, copy to %LOCALAPPDATA%\\Roblox\\Plugins
Run: python tools/build.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
DIST = os.path.join(ROOT, "dist")
MODULES = ["Joints", "PoseMath", "Presets", "Rig", "Resolve", "Validator", "Builder", "Preview", "Examples"]


def read(*parts):
    with open(os.path.join(SRC, *parts), encoding="utf-8") as f:
        return f.read()


def long_string(text):
    level = 1
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def installer():
    lines = [
        "-- AnimKit installer (generated by tools/build.py). Run in Edit mode via MCP execute_luau.",
        "-- Creates ServerStorage.AnimKit. Replaces it only if it was made by this installer.",
        "local ServerStorage = game:GetService('ServerStorage')",
        "local old = ServerStorage:FindFirstChild('AnimKit')",
        "if old and not old:GetAttribute('AnimKitInstall') then",
        "  error('ServerStorage.AnimKit exists and was not made by the AnimKit installer; not touching it')",
        "end",
        "local function mod(name, src, parent)",
        "  local m = Instance.new('ModuleScript')",
        "  m.Name = name",
        "  m.Source = src",
        "  m.Parent = parent",
        "  return m",
        "end",
        "local root = Instance.new('ModuleScript')",
        "root.Name = 'AnimKit'",
        "root.Source = " + long_string(read("AnimKit", "init.lua")),
        "root:SetAttribute('AnimKitInstall', true)",
    ]
    for name in MODULES:
        lines.append("mod('%s', %s, root)" % (name, long_string(read("AnimKit", name + ".lua"))))
    lines += [
        "if old then old:Destroy() end",
        "root.Parent = ServerStorage",
        "return 'AnimKit installed at ' .. root:GetFullName()",
    ]
    return "\n".join(lines) + "\n"


def xml_item(cls, name, source, children, counter):
    if "]]>" in source:
        raise ValueError(name + " contains ']]>' which breaks CDATA")
    counter[0] += 1
    ref = "RBX%d" % counter[0]
    out = ['<Item class="%s" referent="%s"><Properties>' % (cls, ref),
           '<string name="Name">%s</string>' % name,
           '<ProtectedString name="Source"><![CDATA[%s]]></ProtectedString>' % source,
           '</Properties>']
    out += children
    out.append("</Item>")
    return "\n".join(out)


def animkit_item(counter):
    kids = [xml_item("ModuleScript", n, read("AnimKit", n + ".lua"), [], counter) for n in MODULES]
    return xml_item("ModuleScript", "AnimKit", read("AnimKit", "init.lua"), kids, counter)


def wrap(item):
    return ('<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
            'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
            'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">\n'
            + item + "\n</roblox>\n")


def main():
    os.makedirs(DIST, exist_ok=True)
    with open(os.path.join(DIST, "install_animkit.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write(installer())
    counter = [0]
    with open(os.path.join(DIST, "AnimKit.rbxmx"), "w", encoding="utf-8", newline="\n") as f:
        f.write(wrap(animkit_item(counter)))
    counter = [0]
    ui = xml_item("ModuleScript", "Ui", read("Plugin", "Ui.lua"), [], counter)
    kit = animkit_item(counter)
    plugin = xml_item("Script", "AnimKitPlugin", read("Plugin", "Main.server.lua"), [ui, kit], counter)
    with open(os.path.join(DIST, "AnimKitPlugin.rbxmx"), "w", encoding="utf-8", newline="\n") as f:
        f.write(wrap(plugin))
    # line count guard (keep modules small)
    for folder in ("AnimKit", "Plugin"):
        for fn in sorted(os.listdir(os.path.join(SRC, folder))):
            n = read(folder, fn).count("\n")
            print("%-28s %4d lines%s" % (folder + "/" + fn, n, "  <-- over 250" if n > 250 else ""))
    print("built:", ", ".join(sorted(os.listdir(DIST))))


if __name__ == "__main__":
    main()
